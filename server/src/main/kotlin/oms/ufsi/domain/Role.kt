package oms.ufsi.domain

/**
 * Доменна модель ролі користувача.
 *
 * Доменні моделі описують предметну область
 * і не повинні залежати від деталей зберігання даних.
 */
data class Role(

    /**
     * Унікальний ідентифікатор ролі.
     */
    val id: Long,

    /**
     * Системний код ролі.
     */
    val code: String,

    /**
     * Назва ролі.
     */
    val name: String
)